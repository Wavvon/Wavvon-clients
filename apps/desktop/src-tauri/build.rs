use std::fs;

/// The one command a mini-app window may call; the main window never gets it.
const MINI_APP_COMMANDS: &[&str] = &["mini_app_voice_position"];

/// Every command registered in `generate_handler!` in src/lib.rs, by its last
/// path segment, so the list there stays the only list.
fn app_commands() -> Vec<String> {
    let lib = fs::read_to_string("src/lib.rs").expect("read src/lib.rs");
    let start = lib
        .find("generate_handler![")
        .expect("generate_handler! in src/lib.rs");
    let body = &lib[start + "generate_handler![".len()..];
    let body = &body[..body.find(']').expect("end of generate_handler!")];
    body.lines()
        .map(|l| l.split("//").next().unwrap_or("").trim())
        .flat_map(|l| l.split(','))
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(|s| s.rsplit("::").next().unwrap().to_string())
        .collect()
}

fn main() {
    println!("cargo:rerun-if-changed=src/lib.rs");
    let commands = app_commands();

    // Declaring an app manifest puts every app command behind the ACL, not
    // only the listed ones: the main window needs a permission for all of
    // them, or every invoke is refused and the window stays blank (it did,
    // from #433 until this). The permission is written here from the same
    // list, so a new command cannot be forgotten.
    let main: Vec<String> = commands
        .iter()
        .filter(|c| !MINI_APP_COMMANDS.contains(&c.as_str()))
        .map(|c| format!("  \"{c}\","))
        .collect();
    let toml = format!(
        "# Generated by build.rs from generate_handler! in src/lib.rs. Do not edit.\n\n\
         [[permission]]\n\
         identifier = \"allow-main-window\"\n\
         description = \"Every app command except the mini-app voice bridge.\"\n\
         commands.allow = [\n{}\n]\n",
        main.join("\n")
    );
    let path = "permissions/main-window.toml";
    if fs::read_to_string(path).ok().as_deref() != Some(toml.as_str()) {
        fs::write(path, toml).expect("write permissions/main-window.toml");
    }

    // AppManifest wants a 'static list; a build script runs once, so leaking is fine.
    let names: &'static [&'static str] = Box::leak(
        commands
            .into_iter()
            .map(|c| &*Box::leak(c.into_boxed_str()))
            .collect::<Vec<_>>()
            .into_boxed_slice(),
    );
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(names)),
    )
    .expect("failed to run tauri-build")
}
